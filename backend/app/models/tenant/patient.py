"""
Patient Model (Tenant Database)
---------------------------------
Represents a patient registered at a hospital.

This is the central record that all clinical operations connect to:
  - Appointments reference patient_id
  - Medical records reference patient_id
  - Prescriptions reference patient_id
  - Lab orders reference patient_id
  - Billing invoices reference patient_id

Data sensitivity: Patient data is Protected Health Information (PHI).
Every query MUST be scoped to hospital_id. No patient data is ever
returned without the hospital_id filter applied.

Patient ID System:
  Each hospital generates its own sequential patient IDs.
  Format: PAT-XXXXX (e.g., PAT-00001, PAT-00042, PAT-10000)
  These IDs are unique within a hospital, not globally.
  The UUID (id field) is the globally unique identifier.

Soft Delete Policy:
  Patients are NEVER hard-deleted from the database.
  is_active=False hides the patient from all normal queries.
  Medical history must be preserved for legal and clinical reasons.
  deactivated_by and deactivated_at record who performed the soft
  delete and when, closing the audit gap flagged in ADR-006.
"""

import uuid
from datetime import datetime, date
from sqlalchemy import (
    String, Text, Boolean, DateTime, Date,
    Enum as SAEnum, func, UUID, Integer, JSON
)
from sqlalchemy.orm import Mapped, mapped_column
import enum

from app.database import TenantBase


class Gender(str, enum.Enum):
    """Patient biological sex/gender options."""
    MALE = "male"
    FEMALE = "female"
    OTHER = "other"
    PREFER_NOT_TO_SAY = "prefer_not_to_say"


class BloodType(str, enum.Enum):
    """
    ABO blood group system with Rh factor.
    Critical for transfusions and surgical planning.
    """
    A_POSITIVE = "A+"
    A_NEGATIVE = "A-"
    B_POSITIVE = "B+"
    B_NEGATIVE = "B-"
    AB_POSITIVE = "AB+"
    AB_NEGATIVE = "AB-"
    O_POSITIVE = "O+"
    O_NEGATIVE = "O-"
    UNKNOWN = "unknown"


class MaritalStatus(str, enum.Enum):
    SINGLE = "single"
    MARRIED = "married"
    DIVORCED = "divorced"
    WIDOWED = "widowed"
    SEPARATED = "separated"
    OTHER = "other"


class Patient(TenantBase):
    """
    Patient table in the tenant database.

    One row per patient per hospital.
    The hospital_id column is the tenant isolation key.
    """
    __tablename__ = "patients"

    # ── Primary Key ───────────────────────────────────────────────────────────
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # ── Tenant Key ────────────────────────────────────────────────────────────
    # CRITICAL: Every query against patients MUST filter by hospital_id.
    hospital_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
        index=True,
    )

    # ── Human-Readable Patient ID ─────────────────────────────────────────────
    # Sequential within each hospital. Format: PAT-00001
    # Generated by the service layer, not the database.
    # Indexed because staff search by this ID frequently.
    patient_number: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        index=True,
    )

    # ── Personal Information ──────────────────────────────────────────────────
    first_name: Mapped[str] = mapped_column(String(100), nullable=False)
    last_name: Mapped[str] = mapped_column(String(100), nullable=False)

    # Middle name is optional but useful in regions where it is common
    middle_name: Mapped[str | None] = mapped_column(String(100), nullable=True)

    date_of_birth: Mapped[date | None] = mapped_column(Date, nullable=True)

    gender: Mapped[Gender | None] = mapped_column(
        SAEnum(Gender),
        nullable=True,
    )

    marital_status: Mapped[MaritalStatus | None] = mapped_column(
        SAEnum(MaritalStatus),
        nullable=True,
    )

    # National ID, passport number, or any government-issued ID
    # Used for identity verification and duplicate detection
    national_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,  # Staff search by national ID
    )

    # ── Contact Information ───────────────────────────────────────────────────
    phone_primary: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
        index=True,  # Staff search by phone number
    )
    phone_secondary: Mapped[str | None] = mapped_column(String(50), nullable=True)

    email: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
        index=True,
    )

    # ── Address ───────────────────────────────────────────────────────────────
    address_line1: Mapped[str | None] = mapped_column(String(255), nullable=True)
    address_line2: Mapped[str | None] = mapped_column(String(255), nullable=True)
    city: Mapped[str | None] = mapped_column(String(100), nullable=True)
    state: Mapped[str | None] = mapped_column(String(100), nullable=True)
    country: Mapped[str | None] = mapped_column(String(100), nullable=True)

    # ── Medical Background ────────────────────────────────────────────────────
    blood_type: Mapped[BloodType | None] = mapped_column(
        SAEnum(BloodType),
        nullable=True,
    )

    # JSON arrays stored as JSONB in PostgreSQL
    # This avoids creating separate tables for what are essentially
    # simple lists of strings at this stage of development.
    #
    # allergies example:
    #   ["Penicillin", "Sulfa drugs", "Latex"]
    #
    # chronic_conditions example:
    #   ["Type 2 Diabetes", "Hypertension", "Asthma"]
    #
    # current_medications example:
    #   ["Metformin 500mg", "Lisinopril 10mg"]
    allergies: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    chronic_conditions: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    current_medications: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    # Free-text field for additional medical notes at registration
    medical_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # ── Emergency Contact ─────────────────────────────────────────────────────
    # Who to contact if the patient is incapacitated
    emergency_contact_name: Mapped[str | None] = mapped_column(
        String(255), nullable=True
    )
    emergency_contact_relationship: Mapped[str | None] = mapped_column(
        String(100), nullable=True
    )
    emergency_contact_phone: Mapped[str | None] = mapped_column(
        String(50), nullable=True
    )

    # ── Insurance ─────────────────────────────────────────────────────────────
    # Basic insurance fields — detailed insurance management comes in billing
    insurance_provider: Mapped[str | None] = mapped_column(
        String(255), nullable=True
    )
    insurance_number: Mapped[str | None] = mapped_column(
        String(100), nullable=True
    )

    # ── Occupation ────────────────────────────────────────────────────────────
    # Relevant for occupational health assessments
    occupation: Mapped[str | None] = mapped_column(String(255), nullable=True)
    employer: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # ── Registration & Audit Metadata ─────────────────────────────────────────
    # Who registered this patient (references hospital_users.id)
    registered_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )

    # Who last updated this record (references hospital_users.id)
    # Populated by the service layer on every update operation.
    # Closes the audit gap documented in ADR-006.
    updated_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )

    # Who deactivated this patient (references hospital_users.id)
    # Populated when is_active is set to False.
    # Null for active patients and for patients deactivated before this
    # column was added (legacy rows).
    deactivated_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )

    # When this patient was deactivated (soft-deleted)
    deactivated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # Primary doctor assigned to this patient (references hospital_users.id)
    assigned_doctor_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )

    # ── Status ────────────────────────────────────────────────────────────────
    # Soft delete: is_active=False hides patient from normal queries
    # Data is preserved for legal and medical record requirements
    is_active: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True
    )

    # ── Timestamps ────────────────────────────────────────────────────────────
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    def __repr__(self) -> str:
        return (
            f"<Patient id={self.id} "
            f"number='{self.patient_number}' "
            f"name='{self.first_name} {self.last_name}' "
            f"hospital_id={self.hospital_id}>"
        )

    @property
    def full_name(self) -> str:
        """Returns the patient's full name including middle name if present."""
        parts = [self.first_name]
        if self.middle_name:
            parts.append(self.middle_name)
        parts.append(self.last_name)
        return " ".join(parts)

    @property
    def age(self) -> int | None:
        """
        Calculates the patient's current age from date of birth.
        Returns None if date of birth is not recorded.
        """
        if not self.date_of_birth:
            return None
        today = date.today()
        return (
            today.year - self.date_of_birth.year
            - (
                (today.month, today.day)
                < (self.date_of_birth.month, self.date_of_birth.day)
            )
        )