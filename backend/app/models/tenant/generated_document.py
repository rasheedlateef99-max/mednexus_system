"""
Generated Document Model (Tenant Database)
-------------------------------------------------
Audit log of every PDF generated by the hospital. Does not store the
PDF itself — that lives in Cloudflare R2. This row tracks WHAT was
generated, FROM what source record, WHO generated it, and WHERE to
find it.

source_type + source_id together identify the originating record
(an Invoice, Prescription, LabOrder, etc.) without a real foreign key,
since a single documents table spanning five different source tables
would need five nullable FK columns — same cross-reference pattern
used throughout this project (Invoice.appointment_id, etc.) rather
than introducing a polymorphic association anti-pattern.
"""

import uuid
from datetime import datetime
from sqlalchemy import String, DateTime, Enum as SAEnum, func, UUID
from sqlalchemy.orm import Mapped, mapped_column
import enum

from app.database import TenantBase


class DocumentType(str, enum.Enum):
    INVOICE = "invoice"
    RECEIPT = "receipt"
    PRESCRIPTION = "prescription"
    LAB_REPORT = "lab_report"
    MEDICAL_CERTIFICATE = "medical_certificate"
    REFERRAL_LETTER = "referral_letter"
    DISCHARGE_SUMMARY = "discharge_summary"


class GeneratedDocument(TenantBase):
    __tablename__ = "generated_documents"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4,
    )

    hospital_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False, index=True)
    patient_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)

    document_type: Mapped[DocumentType] = mapped_column(SAEnum(DocumentType), nullable=False, index=True)

    # The source record this document was generated from
    source_type: Mapped[str] = mapped_column(String(50), nullable=False)
    source_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False, index=True)

    # Where the actual PDF bytes live in R2
    storage_key: Mapped[str] = mapped_column(String(500), nullable=False)
    file_size_bytes: Mapped[int | None] = mapped_column(nullable=True)

    generated_by: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False,
    )

    def __repr__(self) -> str:
        return f"<GeneratedDocument id={self.id} type={self.document_type} source_id={self.source_id}>"